def _validate_config(config: TrainConfig) -> None:
    if config.initialization_mode not in {"pretrain", "load"}:
        raise ValueError("initialization_mode must be 'pretrain' or 'load'.")
    if config.offline_algorithm not in {"cql", "calql"}:
        raise ValueError("offline_algorithm must be 'cql' or 'calql'.")
    if config.initialization_mode == "load" and not config.pretrained_checkpoint:
        raise ValueError("pretrained_checkpoint is required when initialization_mode='load'.")
    if config.num_critics < 1:
        raise ValueError("num_critics must be positive.")
    for value, name in (
        (config.pretrain_num_min_qs, "pretrain_num_min_qs"),
        (int(config.online_num_min_qs), "online_num_min_qs"),
    ):
        if value < 1 or value > config.num_critics:
            raise ValueError(f"{name} must be in [1, num_critics].")
    if config.minibatch_size < 1 or config.utd_ratio < 1:
        raise ValueError("minibatch_size and utd_ratio must be positive.")
    if config.cql_n_actions < 1 or config.target_backup_n_actions < 1:
        raise ValueError("cql_n_actions and target_backup_n_actions must be positive.")
    if config.warmup_steps < config.minibatch_size * config.utd_ratio:
        raise ValueError(
            "warmup_steps must be at least minibatch_size * utd_ratio so the "
            "first WSRL update can sample a complete online super-batch."
        )
    if not math.isclose(config.offline_data_ratio_online, 0.0, abs_tol=1e-12):
        raise ValueError(
            "This file implements the main no-retention WSRL setting. "
            "offline_data_ratio_online must be 0.0."
        )
    if config.std_parameterization not in {"uniform", "exp"}:
        raise ValueError("std_parameterization must be 'uniform' or 'exp'.")
    if config.dataset_source not in {"d4rl", "adroit_binary"}:
        raise ValueError("dataset_source must be 'd4rl' or 'adroit_binary'.")


