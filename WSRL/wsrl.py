def train(config: TrainConfig) -> None:
    _resolve_official_preset(config)
    _validate_config(config)
    _set_seed(config.train_seed, config.deterministic_torch)
    device = torch.device(config.device)

    train_env = wrap_env(gym.make(config.env_name), config, training=True)
    eval_env = wrap_env(gym.make(config.env_name), config, training=False)
    _seed_env(train_env, config.train_seed)
    _seed_env(eval_env, config.train_seed + config.eval_seed_offset)

    if not isinstance(train_env.observation_space, gym.spaces.Box):
        raise TypeError("Wrapped observation space must be Box.")
    if not isinstance(train_env.action_space, gym.spaces.Box):
        raise TypeError("Wrapped action space must be Box.")
    observation_dim = int(np.prod(train_env.observation_space.shape))
    action_dim = int(np.prod(train_env.action_space.shape))

    actor = TanhGaussianActor(
        observation_dim,
        action_dim,
        config.actor_hidden_dims,
        config.std_parameterization,
        config,
    ).to(device)
    critic = CriticEnsemble(
        observation_dim,
        action_dim,
        config.critic_hidden_dims,
        config.num_critics,
        config,
    ).to(device)
    learner = WSRLLearner(actor, critic, action_dim, config, device)

    run_name = (
        f"{config.env_name}_seed{config.train_seed}_"
        f"Q{config.num_critics}_UTD{config.utd_ratio}"
    )
    log_dir = Path(config.log_root) / config.env_name.split("-")[0] / run_name
    log_dir.mkdir(parents=True, exist_ok=True)
    writer = SummaryWriter(log_dir=str(log_dir))

    print(
        f"env={config.env_name}\n"
        f"preset={_preset_label(config.env_name)}\n"
        f"device={device}\n"
        f"initialization={config.initialization_mode}/{config.offline_algorithm}\n"
        f"dataset_source={config.dataset_source}, reward_transform="
        f"{config.reward_scale}*r+{config.reward_bias}\n"
        f"actor_hidden={config.actor_hidden_dims}\n"
        f"critic_hidden={config.critic_hidden_dims}\n"
        f"critics={config.num_critics}, online_num_min_qs={config.online_num_min_qs}\n"
        f"online_max_target_backup={config.max_target_backup}, "
        f"offline_cql_max_target_backup={config.cql_max_target_backup}\n"
        f"warmup_steps={config.warmup_steps}\n"
        f"online updates/env-step: critic={config.utd_ratio}, actor=1, temperature=1\n"
        f"critic mini-batch={config.minibatch_size}, actor super-batch="
        f"{config.minibatch_size * config.utd_ratio}\n"
        f"offline data retained online=0\n"
        f"log_dir={log_dir}",
        flush=True,
    )

    # ------------------------------------------------------------------
    # Phase 1: offline initialization
    # ------------------------------------------------------------------
    if config.initialization_mode == "load":
        checkpoint = learner.load_checkpoint(
            config.pretrained_checkpoint,
            strict=config.strict_checkpoint,
            restore_optimizer_states=config.restore_optimizer_states,
        )
        print(
            f"Loaded pre-trained checkpoint: {config.pretrained_checkpoint} "
            f"(phase={checkpoint.get('phase', 'unknown')}, "
            f"step={checkpoint.get('step', 'unknown')})",
            flush=True,
        )
    else:
        if config.dataset_source == "adroit_binary":
            arrays = _load_adroit_binary_dataset(config)
        else:
            arrays = _load_d4rl_dataset(train_env, config)
        offline_dataset = ArrayDataset(arrays, seed=config.dataset_seed)
        use_calql = config.offline_algorithm == "calql"

        for step in trange(int(config.pretrain_steps), desc="Offline initialization"):
            batch = _to_torch_batch(
                offline_dataset.sample(config.minibatch_size), device
            )
            metrics = learner.update_offline(batch, use_calql=use_calql)

            if step % config.log_every == 0:
                for key, value in metrics.items():
                    writer.add_scalar(f"offline-training/{key}", value, step)
            if step % config.eval_every == 0:
                evaluation = evaluate(
                    learner.actor,
                    eval_env,
                    device,
                    config.eval_episodes,
                    config.env_name,
                )
                for key, value in evaluation.items():
                    writer.add_scalar(f"offline-evaluation/{key}", value, step)
                writer.flush()

        _save_checkpoint(
            learner,
            config,
            run_name,
            "offline_pretrained",
            int(config.pretrain_steps),
        )

        # The main WSRL setting explicitly does not retain offline transitions.
        del offline_dataset
        del arrays

    learner.switch_to_online_wsrl()

    offline_evaluation = evaluate(
        learner.actor,
        eval_env,
        device,
        config.eval_episodes,
        config.env_name,
    )
    pretrained_message = (
        f"[pretrained evaluation] return={offline_evaluation['return']:.3f}, "
        f"length={offline_evaluation['length']:.1f}"
    )
    for key in ("d4rl_normalized_score", "success_rate", "num_stages_solved"):
        if key in offline_evaluation:
            pretrained_message += f", {key}={offline_evaluation[key]:.3f}"
    print(pretrained_message, flush=True)

    # Frozen policy used only during the warm-up interaction phase.
    frozen_pretrained_actor = deepcopy(learner.actor).to(device)
    frozen_pretrained_actor.eval()
    frozen_pretrained_actor.requires_grad_(False)

    replay_buffer = ReplayBuffer(
        train_env.observation_space,
        train_env.action_space,
        config.replay_buffer_capacity,
        seed=config.train_seed,
    )

    # ------------------------------------------------------------------
    # Phases 2 and 3: warm-up, then online-only high-UTD SAC
    # ------------------------------------------------------------------
    observation = _reset_env(train_env)
    episode_return = 0.0
    episode_length = 0
    super_batch_size = config.minibatch_size * config.utd_ratio

    for online_step in trange(config.online_steps, desc="WSRL online fine-tuning"):
        if online_step < config.warmup_steps:
            action = frozen_pretrained_actor.sample_action(observation, device)
        else:
            action = learner.actor.sample_action(observation, device)
        if _env_type(config.env_name) in {"antmaze", "kitchen", "locomotion", "adroit_d4rl"}:
            action = np.clip(action, -config.clip_action, config.clip_action)

        (
            next_observation,
            reward,
            terminated,
            truncated,
            info,
        ) = _step_env(train_env, action)
        done = bool(terminated or truncated)
        mask = 0.0 if terminated else 1.0
        replay_buffer.insert(
            observation,
            action,
            reward,
            mask,
            done,
            next_observation,
        )

        episode_return += reward
        episode_length += 1
        observation = next_observation
        if done:
            writer.add_scalar("online-training/episode_return", episode_return, online_step)
            writer.add_scalar("online-training/episode_length", episode_length, online_step)
            observation = _reset_env(train_env)
            episode_return = 0.0
            episode_length = 0

        metrics: Dict[str, float] = {}
        if online_step >= config.warmup_steps:
            super_batch = _to_torch_batch(
                replay_buffer.sample(super_batch_size), device
            )
            metrics = learner.update_high_utd(super_batch)

        if metrics and online_step % config.log_every == 0:
            for key, value in metrics.items():
                writer.add_scalar(f"online-training/{key}", value, online_step)
            writer.add_scalar(
                "online-training/replay_size", replay_buffer.size, online_step
            )
            writer.flush()

        if (
            online_step % config.eval_every == 0
            or online_step == config.warmup_steps
            or online_step == config.online_steps - 1
        ):
            evaluation = evaluate(
                learner.actor,
                eval_env,
                device,
                config.eval_episodes,
                config.env_name,
            )
            for key, value in evaluation.items():
                writer.add_scalar(f"online-evaluation/{key}", value, online_step)
            message = (
                f"[online eval] step={online_step}, "
                f"return={evaluation['return']:.3f}, "
                f"length={evaluation['length']:.1f}"
            )
            for key in ("d4rl_normalized_score", "success_rate", "num_stages_solved"):
                if key in evaluation:
                    message += f", {key}={evaluation[key]:.3f}"
            print(message, flush=True)
            writer.flush()

        if (
            config.checkpoints_path is not None
            and online_step > 0
            and online_step % config.save_every == 0
        ):
            _save_checkpoint(
                learner, config, run_name, "online", online_step
            )

    _save_checkpoint(
        learner, config, run_name, "final", config.online_steps
    )
    writer.close()
    train_env.close()
    eval_env.close()


if __name__ == "__main__":
    train(pyrallis.parse(config_class=TrainConfig))
