"""Single-file PyTorch reproduction of WSRL.

WSRL: Efficient Online Reinforcement Learning Fine-Tuning Need Not Retain
Offline Data (ICLR 2025).

This file follows the paper and the author-released JAX/Flax repository while
keeping the same single-file PyTorch style used by the surrounding baselines.
It implements the full state-based experimental pipeline:

1. Initialize the actor and critic from offline RL pre-training. A compatible
   PyTorch checkpoint can be loaded directly, or the file can perform the main
   paper pre-training choice itself: Cal-QL for AntMaze/Adroit/Kitchen and CQL
   for MuJoCo locomotion.
2. Discard the offline dataset and initialize an empty online replay buffer.
3. Collect ``warmup_steps`` transitions with a frozen copy of the pre-trained
   policy and perform no gradient updates.
4. Continue interaction with the trainable policy and optimize standard SAC
   using online data only. Each environment step samples one super-batch,
   performs ``utd_ratio`` critic/target updates on disjoint mini-batches, then
   performs one actor and one temperature update on the entire super-batch.

Released/main-paper WSRL details represented here:

* 5,000 online warm-up steps with the frozen pre-trained policy.
* No offline transition retention during the WSRL fine-tuning phase.
* 10 Q-functions and LayerNorm after every hidden affine layer.
* UTD=4 with mini-batch size 256. The sampled super-batch therefore contains
  1,024 transitions; it is split into four critic mini-batches, while the actor
  and entropy temperature are updated once on all 1,024 transitions.
* Actor LR 1e-4, critic LR 3e-4, temperature LR 1e-4.
* Target entropy ``-action_dim``, discount 0.99, and Polyak coefficient 0.005.
* Entropy is used in the actor objective but not in the Bellman backup.
* AntMaze uses a state-independent policy standard deviation and max-Q target
  backup over 10 policy actions. WSRL uses a 10-Q ensemble and randomly
  subsamples two target critics (with replacement) before taking their minimum
  in every supported domain, including AntMaze.
* Offline actor/critic/temperature optimizer states are retained when switching
  to WSRL online fine-tuning.

The optional offline pre-training implementation uses the released CQL/Cal-QL
settings with the same actor/critic architecture as the WSRL checkpoint. WSRL
itself is agnostic to the offline algorithm; loading a checkpoint generated by
another faithful offline RL implementation is also supported.

PyTorch and JAX/Flax have different PRNG streams, parameter layouts, and
low-level kernels. Therefore this is an algorithmically faithful PyTorch port,
not a bitwise numerical reproduction.

Typical direct run::

    python warl.py --env_name=antmaze-umaze-v2 --train_seed=0

Environment-dependent settings are selected automatically from ``env_name`` when
``official_preset=True``. For AntMaze/MuJoCo and Adroit-Binary this follows the
released WSRL setup. For the standard D4RL Adroit human/cloned/expert tasks used
in the unified RLPD benchmark, the WSRL mechanism is retained but the dataset,
reward, termination, and evaluation protocol are adapted to standard D4RL.
General experiment controls remain available as command-line arguments.
"""

