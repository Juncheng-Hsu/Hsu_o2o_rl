@contextmanager
def _frozen_parameters(module: nn.Module):
    parameters = list(module.parameters())
    previous = [parameter.requires_grad for parameter in parameters]
    try:
        for parameter in parameters:
            parameter.requires_grad_(False)
        yield
    finally:
        for parameter, requires_grad in zip(parameters, previous):
            parameter.requires_grad_(requires_grad)


def _soft_update(target: nn.Module, source: nn.Module, tau: float) -> None:
    with torch.no_grad():
        for target_parameter, source_parameter in zip(
            target.parameters(), source.parameters()
        ):
            target_parameter.mul_(1.0 - tau).add_(source_parameter, alpha=tau)


def _inverse_softplus(value: float) -> float:
    return math.log(math.expm1(float(value)))


class WSRLLearner:
    def __init__(
        self,
        actor: TanhGaussianActor,
        critic: CriticEnsemble,
        action_dim: int,
        config: TrainConfig,
        device: torch.device,
    ):
        self.actor = actor
        self.critic = critic
        self.target_critic = deepcopy(critic).to(device)
        self.target_critic.requires_grad_(False)
        self.config = config
        self.device = device
        self.action_dim = int(action_dim)

        self.actor_optimizer = torch.optim.Adam(
            self.actor.parameters(), lr=config.actor_learning_rate
        )
        self.critic_optimizer = torch.optim.Adam(
            self.critic.parameters(), lr=config.critic_learning_rate
        )

        self.raw_temperature = torch.tensor(
            _inverse_softplus(config.init_temperature),
            dtype=torch.float32,
            device=device,
            requires_grad=True,
        )
        self.temperature_optimizer = torch.optim.Adam(
            [self.raw_temperature], lr=config.temperature_learning_rate
        )

        self.raw_cql_alpha_prime: Optional[torch.Tensor]
        self.cql_alpha_prime_optimizer: Optional[torch.optim.Optimizer]
        if bool(config.cql_autotune_alpha):
            self.raw_cql_alpha_prime = torch.tensor(
                _inverse_softplus(config.cql_alpha_prime_init),
                dtype=torch.float32,
                device=device,
                requires_grad=True,
            )
            self.cql_alpha_prime_optimizer = torch.optim.Adam(
                [self.raw_cql_alpha_prime],
                lr=config.cql_alpha_prime_learning_rate,
            )
        else:
            self.raw_cql_alpha_prime = None
            self.cql_alpha_prime_optimizer = None

        self.target_entropy = (
            -float(action_dim)
            if config.target_entropy is None or config.target_entropy >= 0.0
            else float(config.target_entropy)
        )
        self.num_min_qs = int(config.pretrain_num_min_qs)
        self.max_target_backup = bool(config.max_target_backup)

    @property
    def temperature(self) -> torch.Tensor:
        return F.softplus(self.raw_temperature)

    @property
    def cql_alpha_prime(self) -> Optional[torch.Tensor]:
        if self.raw_cql_alpha_prime is None:
            return None
        return F.softplus(self.raw_cql_alpha_prime)

    def switch_to_online_wsrl(self) -> None:
        self.num_min_qs = int(self.config.online_num_min_qs)
        self.max_target_backup = bool(self.config.max_target_backup)

    def _sample_target_indices(self) -> Optional[torch.Tensor]:
        if self.num_min_qs >= self.critic.ensemble_size:
            return None
        # Official JAX code uses randint, so sampling is with replacement.
        return torch.randint(
            low=0,
            high=self.critic.ensemble_size,
            size=(self.num_min_qs,),
            device=self.device,
        )

    def _target_q(
        self,
        batch: TorchBatch,
        *,
        max_target_backup: Optional[bool] = None,
        n_backup_actions: Optional[int] = None,
    ) -> torch.Tensor:
        """Compute the SAC target with released WSRL/CQL backup semantics.

        Online WSRL uses ``self.max_target_backup`` (True only for AntMaze).
        Offline CQL/Cal-QL instead passes ``cql_max_target_backup=True`` and
        ``cql_n_actions=10`` regardless of the online setting.
        """
        use_max_backup = (
            self.max_target_backup
            if max_target_backup is None
            else bool(max_target_backup)
        )
        if n_backup_actions is None:
            n_backup_actions = self.config.target_backup_n_actions

        with torch.no_grad():
            indices = self._sample_target_indices()
            if use_max_backup:
                next_actions, next_log_probs = self.actor.sample(
                    batch["next_observations"],
                    repeat=int(n_backup_actions),
                    reparameterize=False,
                )
                target_next_qs = self.target_critic(
                    batch["next_observations"], next_actions, indices=indices
                )
                # Released code: subsample critics -> min across critics -> max
                # across the sampled next actions.
                target_next_q = target_next_qs.min(dim=0).values
                max_indices = target_next_q.argmax(dim=-1, keepdim=True)
                target_next_q = target_next_q.gather(-1, max_indices).squeeze(-1)
                selected_log_prob = next_log_probs.gather(
                    -1, max_indices
                ).squeeze(-1)
                if self.config.backup_entropy:
                    target_next_q = (
                        target_next_q
                        - self.temperature.detach() * selected_log_prob
                    )
            else:
                next_actions, next_log_prob = self.actor.sample(
                    batch["next_observations"], reparameterize=False
                )
                target_next_qs = self.target_critic(
                    batch["next_observations"], next_actions, indices=indices
                )
                target_next_q = target_next_qs.min(dim=0).values
                if self.config.backup_entropy:
                    target_next_q = (
                        target_next_q
                        - self.temperature.detach() * next_log_prob
                    )

            return (
                batch["rewards"]
                + self.config.discount * batch["masks"] * target_next_q
            )

    def update_critic(self, batch: TorchBatch) -> Dict[str, float]:
        target_q = self._target_q(batch)
        predicted_qs = self.critic(batch["observations"], batch["actions"])
        critic_loss = (predicted_qs - target_q.unsqueeze(0)).pow(2).mean()

        self.critic_optimizer.zero_grad(set_to_none=True)
        critic_loss.backward()
        self.critic_optimizer.step()
        _soft_update(self.target_critic, self.critic, self.config.tau)

        return {
            "critic_loss": float(critic_loss.detach().item()),
            "predicted_q": float(predicted_qs.detach().mean().item()),
            "target_q": float(target_q.detach().mean().item()),
        }

    def update_actor_temperature(self, batch: TorchBatch) -> Dict[str, float]:
        actions, log_prob = self.actor.sample(
            batch["observations"], reparameterize=True
        )
        with _frozen_parameters(self.critic):
            q_values = self.critic(batch["observations"], actions).min(dim=0).values
        actor_loss = (
            self.temperature.detach() * log_prob - q_values
        ).mean()

        # Official temperature update draws actions at next observations.
        with torch.no_grad():
            _, next_log_prob = self.actor.sample(
                batch["next_observations"], reparameterize=False
            )
            entropy = -next_log_prob.mean()
        temperature_loss = self.temperature * (
            entropy - self.target_entropy
        )

        self.actor_optimizer.zero_grad(set_to_none=True)
        self.temperature_optimizer.zero_grad(set_to_none=True)
        actor_loss.backward()
        temperature_loss.backward()
        self.actor_optimizer.step()
        self.temperature_optimizer.step()

        return {
            "actor_loss": float(actor_loss.detach().item()),
            "temperature_loss": float(temperature_loss.detach().item()),
            "temperature": float(self.temperature.detach().item()),
            "entropy": float(entropy.detach().item()),
        }

    def update_high_utd(self, super_batch: TorchBatch) -> Dict[str, float]:
        """Official WSRL/RLPD high-UTD schedule.

        The super-batch has ``minibatch_size * utd_ratio`` samples. Critic and
        target critic are updated sequentially on every mini-batch. Actor and
        temperature are then updated once on the complete super-batch.
        """
        total_size = next(iter(super_batch.values())).shape[0]
        if total_size % self.config.utd_ratio != 0:
            raise ValueError("Super-batch size must be divisible by utd_ratio.")
        mini_size = total_size // self.config.utd_ratio
        if mini_size != self.config.minibatch_size:
            raise ValueError(
                f"Expected mini-batch size {self.config.minibatch_size}, got {mini_size}."
            )

        critic_metrics: Dict[str, List[float]] = {}
        for update_index in range(self.config.utd_ratio):
            start = update_index * mini_size
            end = start + mini_size
            mini_batch = {key: value[start:end] for key, value in super_batch.items()}
            info = self.update_critic(mini_batch)
            for key, value in info.items():
                critic_metrics.setdefault(key, []).append(value)

        metrics = {
            key: float(np.mean(values)) for key, values in critic_metrics.items()
        }
        metrics.update(self.update_actor_temperature(super_batch))
        return metrics

    def _cql_penalty(
        self,
        batch: TorchBatch,
        q_data: torch.Tensor,
        use_calql: bool,
    ) -> Tuple[torch.Tensor, Dict[str, torch.Tensor]]:
        batch_size = batch["observations"].shape[0]
        n_actions = self.config.cql_n_actions

        random_actions = torch.empty(
            batch_size, n_actions, self.action_dim, device=self.device
        ).uniform_(-1.0, 1.0)
        random_log_density = self.action_dim * math.log(0.5)

        with torch.no_grad():
            current_actions, current_log_probs = self.actor.sample(
                batch["observations"], repeat=n_actions, reparameterize=False
            )
            next_actions, next_log_probs = self.actor.sample(
                batch["next_observations"], repeat=n_actions, reparameterize=False
            )

        q_random = self.critic(batch["observations"], random_actions)
        q_current = self.critic(batch["observations"], current_actions)
        # Released CQL evaluates actions proposed at s' using the current state s.
        q_next = self.critic(batch["observations"], next_actions)

        # The released REDQ+CQL implementation applies the conservative
        # regularizer to a randomly sampled critic subset, while the Bellman
        # loss still trains the full ensemble. Sampling uses randint and may
        # therefore contain duplicate critic indices.
        if self.config.pretrain_num_min_qs < self.critic.ensemble_size:
            cql_indices = torch.randint(
                0,
                self.critic.ensemble_size,
                (self.config.pretrain_num_min_qs,),
                device=self.device,
            )
            q_random = q_random.index_select(0, cql_indices)
            q_current = q_current.index_select(0, cql_indices)
            q_next = q_next.index_select(0, cql_indices)
            q_data_cql = q_data.index_select(0, cql_indices)
        else:
            q_data_cql = q_data

        if use_calql:
            if "mc_returns" not in batch:
                raise KeyError("Cal-QL pre-training requires mc_returns.")
            lower_bound = batch["mc_returns"].view(1, batch_size, 1)
            q_current = torch.maximum(q_current, lower_bound)
            q_next = torch.maximum(q_next, lower_bound)

        if bool(self.config.cql_importance_sample):
            candidates = torch.cat(
                [
                    q_random - random_log_density,
                    q_current - current_log_probs.unsqueeze(0),
                    q_next - next_log_probs.unsqueeze(0),
                ],
                dim=-1,
            )
        else:
            candidates = torch.cat(
                [q_random, q_current, q_next, q_data_cql.unsqueeze(-1)], dim=-1
            )
            # Official non-importance-sampled CQL normalizes the finite action
            # set inside log-sum-exp.
            candidates = candidates - (
                math.log(candidates.shape[-1])
                * float(self.config.cql_temperature)
            )

        temperature = float(self.config.cql_temperature)
        q_ood = temperature * torch.logsumexp(candidates / temperature, dim=-1)
        q_diff = (q_ood - q_data_cql).clamp(
            self.config.cql_clip_diff_min,
            self.config.cql_clip_diff_max,
        )

        if bool(self.config.cql_autotune_alpha):
            alpha_prime = self.cql_alpha_prime
            if alpha_prime is None:
                raise RuntimeError("CQL alpha-prime was not initialized.")
            gap = float(self.config.cql_target_action_gap)
            cql_penalty = alpha_prime.detach() * (q_diff.mean() - gap)
            alpha_prime_loss = -alpha_prime * (
                q_diff.detach().mean() - gap
            )
        else:
            cql_penalty = float(self.config.cql_alpha) * q_diff.mean()
            alpha_prime_loss = torch.zeros((), device=self.device)

        return cql_penalty, {
            "cql_diff": q_diff.mean(),
            "cql_ood_q": q_ood.mean(),
            "cql_alpha_prime_loss": alpha_prime_loss,
        }

    def update_offline(self, batch: TorchBatch, use_calql: bool) -> Dict[str, float]:
        """CQL/Cal-QL initialization update while preserving optimizer states."""
        actions, log_prob = self.actor.sample(
            batch["observations"], reparameterize=True
        )
        with _frozen_parameters(self.critic):
            actor_q = self.critic(batch["observations"], actions).min(dim=0).values
        actor_loss = (
            self.temperature.detach() * log_prob - actor_q
        ).mean()

        with torch.no_grad():
            _, next_log_prob = self.actor.sample(
                batch["next_observations"], reparameterize=False
            )
            entropy = -next_log_prob.mean()
        temperature_loss = self.temperature * (
            entropy - self.target_entropy
        )

        target_q = self._target_q(
            batch,
            max_target_backup=self.config.cql_max_target_backup,
            n_backup_actions=self.config.cql_n_actions,
        )
        q_data = self.critic(batch["observations"], batch["actions"])
        bellman_loss = (q_data - target_q.unsqueeze(0)).pow(2).mean()
        cql_penalty, cql_info = self._cql_penalty(batch, q_data, use_calql)
        critic_loss = bellman_loss + cql_penalty

        self.actor_optimizer.zero_grad(set_to_none=True)
        self.temperature_optimizer.zero_grad(set_to_none=True)
        self.critic_optimizer.zero_grad(set_to_none=True)
        if self.cql_alpha_prime_optimizer is not None:
            self.cql_alpha_prime_optimizer.zero_grad(set_to_none=True)

        actor_loss.backward()
        temperature_loss.backward()
        critic_loss.backward()
        if self.cql_alpha_prime_optimizer is not None:
            cql_info["cql_alpha_prime_loss"].backward()

        self.actor_optimizer.step()
        self.temperature_optimizer.step()
        self.critic_optimizer.step()
        if self.cql_alpha_prime_optimizer is not None:
            self.cql_alpha_prime_optimizer.step()
        _soft_update(self.target_critic, self.critic, self.config.tau)

        metrics = {
            "actor_loss": float(actor_loss.detach().item()),
            "temperature_loss": float(temperature_loss.detach().item()),
            "temperature": float(self.temperature.detach().item()),
            "entropy": float(entropy.detach().item()),
            "critic_loss": float(critic_loss.detach().item()),
            "bellman_loss": float(bellman_loss.detach().item()),
            "cql_penalty": float(cql_penalty.detach().item()),
            "predicted_q": float(q_data.detach().mean().item()),
            "target_q": float(target_q.detach().mean().item()),
            "cql_diff": float(cql_info["cql_diff"].detach().item()),
            "cql_ood_q": float(cql_info["cql_ood_q"].detach().item()),
        }
        if self.cql_alpha_prime is not None:
            metrics["cql_alpha_prime"] = float(
                self.cql_alpha_prime.detach().item()
            )
            metrics["cql_alpha_prime_loss"] = float(
                cql_info["cql_alpha_prime_loss"].detach().item()
            )
        return metrics

    def checkpoint(self, config: TrainConfig, phase: str, step: int) -> Dict:
        payload = {
            "actor": self.actor.state_dict(),
            "critic": self.critic.state_dict(),
            "target_critic": self.target_critic.state_dict(),
            "raw_temperature": self.raw_temperature.detach().cpu(),
            "actor_optimizer": self.actor_optimizer.state_dict(),
            "critic_optimizer": self.critic_optimizer.state_dict(),
            "temperature_optimizer": self.temperature_optimizer.state_dict(),
            "phase": phase,
            "step": int(step),
            "config": asdict(config),
        }
        if self.raw_cql_alpha_prime is not None:
            payload["raw_cql_alpha_prime"] = self.raw_cql_alpha_prime.detach().cpu()
        if self.cql_alpha_prime_optimizer is not None:
            payload["cql_alpha_prime_optimizer"] = (
                self.cql_alpha_prime_optimizer.state_dict()
            )
        return payload

    def load_checkpoint(
        self,
        path: str,
        strict: bool,
        restore_optimizer_states: bool,
    ) -> Dict:
        checkpoint = torch.load(path, map_location=self.device)
        self.actor.load_state_dict(checkpoint["actor"], strict=strict)
        self.critic.load_state_dict(checkpoint["critic"], strict=strict)
        if "target_critic" in checkpoint:
            self.target_critic.load_state_dict(
                checkpoint["target_critic"], strict=strict
            )
        else:
            self.target_critic.load_state_dict(self.critic.state_dict())

        if "raw_temperature" in checkpoint:
            with torch.no_grad():
                self.raw_temperature.copy_(
                    torch.as_tensor(
                        checkpoint["raw_temperature"], device=self.device
                    )
                )

        if restore_optimizer_states:
            required = (
                "actor_optimizer",
                "critic_optimizer",
                "temperature_optimizer",
            )
            missing = [key for key in required if key not in checkpoint]
            if missing and strict:
                raise KeyError(
                    "Checkpoint lacks optimizer states required by WSRL: "
                    + ", ".join(missing)
                )
            if "actor_optimizer" in checkpoint:
                self.actor_optimizer.load_state_dict(checkpoint["actor_optimizer"])
            if "critic_optimizer" in checkpoint:
                self.critic_optimizer.load_state_dict(checkpoint["critic_optimizer"])
            if "temperature_optimizer" in checkpoint:
                self.temperature_optimizer.load_state_dict(
                    checkpoint["temperature_optimizer"]
                )
        return checkpoint


