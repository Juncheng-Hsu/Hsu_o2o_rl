def _to_torch_batch(batch: NumpyBatch, device: torch.device) -> TorchBatch:
    output: TorchBatch = {
        "observations": torch.as_tensor(
            batch["observations"], dtype=torch.float32, device=device
        ),
        "actions": torch.as_tensor(
            batch["actions"], dtype=torch.float32, device=device
        ),
        "rewards": torch.as_tensor(
            batch["rewards"], dtype=torch.float32, device=device
        ).reshape(-1),
        "masks": torch.as_tensor(
            batch["masks"], dtype=torch.float32, device=device
        ).reshape(-1),
        "dones": torch.as_tensor(
            batch["dones"], dtype=torch.bool, device=device
        ).reshape(-1),
        "next_observations": torch.as_tensor(
            batch["next_observations"], dtype=torch.float32, device=device
        ),
    }
    if "mc_returns" in batch:
        output["mc_returns"] = torch.as_tensor(
            batch["mc_returns"], dtype=torch.float32, device=device
        ).reshape(-1)
    return output


@torch.no_grad()
def evaluate(
    actor: TanhGaussianActor,
    env: gym.Env,
    device: torch.device,
    episodes: int,
    env_name: str,
) -> Dict[str, float]:
    """Evaluate WSRL with protocol-appropriate metrics.

    Standard D4RL Adroit uses D4RL normalized return for direct comparison
    with the unified RLPD/RiBES benchmark; Adroit-Binary keeps WSRL success.
    """
    env_type = _env_type(env_name)
    returns: List[float] = []
    lengths: List[int] = []
    adroit_binary_successes: List[float] = []
    kitchen_stages: List[float] = []
    normalized_scores: List[float] = []

    actor.eval()
    for _ in range(episodes):
        observation = _reset_env(env)
        terminated = False
        truncated = False
        episode_return = 0.0
        episode_length = 0
        goal_achieved = False
        final_reward = 0.0

        while not (terminated or truncated):
            action = actor.eval_action(observation, device)
            observation, reward, terminated, truncated, info = _step_env(env, action)
            episode_return += reward
            episode_length += 1
            final_reward = float(reward)
            if env_type == "adroit_binary":
                goal_achieved = goal_achieved or bool(info.get("goal_achieved", False))

        returns.append(episode_return)
        lengths.append(episode_length)

        if env_type == "adroit_binary":
            adroit_binary_successes.append(float(goal_achieved))
        elif env_type == "kitchen":
            # Released WSRL evaluation treats the final raw Kitchen reward as
            # the number of solved stages and divides by four for success rate.
            kitchen_stages.append(final_reward)
        elif env_type in {"antmaze", "locomotion", "adroit_d4rl"}:
            normalized = _get_normalized_score(env, episode_return)
            if normalized is not None:
                normalized_scores.append(normalized)

    actor.train()
    result: Dict[str, float] = {
        "return": float(np.mean(returns)),
        "length": float(np.mean(lengths)),
    }
    if adroit_binary_successes:
        result["success_rate"] = float(np.mean(adroit_binary_successes))
    if kitchen_stages:
        stages = float(np.mean(kitchen_stages))
        result["num_stages_solved"] = stages
        result["success_rate"] = stages / 4.0
    if normalized_scores:
        result["d4rl_normalized_score"] = float(np.mean(normalized_scores))
        # For AntMaze, normalized score / 100 is also the success-rate scale
        # used by the released implementation. We do not relabel locomotion as
        # success in TensorBoard, but retain the normalized score for both.
        if env_type == "antmaze":
            result["success_rate"] = result["d4rl_normalized_score"] / 100.0
    return result


def _get_normalized_score(env: gym.Env, raw_return: float) -> Optional[float]:
    candidate = env
    for _ in range(16):
        if hasattr(candidate, "get_normalized_score"):
            try:
                return float(candidate.get_normalized_score(raw_return) * 100.0)
            except Exception:
                return None
        if not hasattr(candidate, "env"):
            break
        candidate = candidate.env
    return None


def _save_checkpoint(
    learner: WSRLLearner,
    config: TrainConfig,
    run_name: str,
    phase: str,
    step: int,
) -> Optional[str]:
    if config.checkpoints_path is None:
        return None
    directory = Path(config.checkpoints_path) / run_name
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{phase}_{step}.pt"
    torch.save(learner.checkpoint(config, phase, step), path)
    return str(path)


def _set_seed(seed: int, deterministic_torch: bool) -> None:
    os.environ["PYTHONHASHSEED"] = str(seed)
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    if deterministic_torch:
        torch.use_deterministic_algorithms(True)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


