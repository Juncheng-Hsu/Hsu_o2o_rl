def _discounted_return_to_go(
    rewards: np.ndarray,
    terminals: np.ndarray,
    discount: float,
    sparse_failure_reward: Optional[float],
) -> np.ndarray:
    rewards = np.asarray(rewards, dtype=np.float32).reshape(-1)
    terminals = np.asarray(terminals, dtype=np.float32).reshape(-1)
    if rewards.shape != terminals.shape:
        raise ValueError("rewards and terminals must have identical shapes.")
    if rewards.size == 0:
        return rewards.copy()

    # Released Cal-QL sparse loader uses the infinite-horizon failure return.
    if sparse_failure_reward is not None and np.allclose(
        rewards, sparse_failure_reward, atol=1e-6, rtol=0.0
    ):
        return np.full_like(
            rewards,
            float(sparse_failure_reward) / (1.0 - float(discount)),
            dtype=np.float32,
        )

    returns = np.empty_like(rewards, dtype=np.float32)
    accumulator = 0.0
    for index in range(len(rewards) - 1, -1, -1):
        accumulator = float(rewards[index]) + float(discount) * accumulator * (
            1.0 - float(terminals[index])
        )
        returns[index] = accumulator
    return returns


def _episode_to_arrays(
    observations: Sequence[np.ndarray],
    actions: Sequence[np.ndarray],
    rewards: Sequence[float],
    next_observations: Sequence[np.ndarray],
    terminals: Sequence[bool],
    config: TrainConfig,
) -> NumpyBatch:
    transformed_rewards = (
        np.asarray(rewards, dtype=np.float32) * float(config.reward_scale)
        + float(config.reward_bias)
    )
    terminals_array = np.asarray(terminals, dtype=np.float32)
    mc_returns = _discounted_return_to_go(
        transformed_rewards,
        terminals_array,
        config.discount,
        config.sparse_failure_reward,
    )
    return {
        "observations": np.asarray(observations, dtype=np.float32),
        "actions": np.clip(
            np.asarray(actions, dtype=np.float32),
            -config.clip_action,
            config.clip_action,
        ),
        "rewards": transformed_rewards,
        "masks": 1.0 - terminals_array,
        "dones": terminals_array.astype(bool),
        "next_observations": np.asarray(next_observations, dtype=np.float32),
        "mc_returns": mc_returns,
    }


def _concatenate_batches(batches: Sequence[NumpyBatch]) -> NumpyBatch:
    nonempty = [batch for batch in batches if len(batch["rewards"]) > 0]
    if not nonempty:
        raise ValueError("Dataset loader produced no transitions.")
    return {
        key: np.concatenate([batch[key] for batch in nonempty], axis=0)
        for key in nonempty[0]
    }


def _load_standard_adroit_d4rl_dataset(
    env: gym.Env, config: TrainConfig
) -> NumpyBatch:
    """Load standard D4RL Adroit with RLPD-compatible qlearning semantics.

    RLPD's D4RL path uses ``d4rl.qlearning_dataset``. We use the same
    transition set for pen/door/hammer/relocate human/cloned/expert and then
    reconstruct trajectory boundaries so Cal-QL can obtain Monte-Carlo returns.
    """
    candidate = env
    for _ in range(16):
        if hasattr(candidate, "get_dataset"):
            break
        if not hasattr(candidate, "env"):
            break
        candidate = candidate.env
    if not hasattr(candidate, "get_dataset"):
        raise AttributeError("The standard D4RL Adroit environment has no get_dataset().")

    raw = d4rl.qlearning_dataset(candidate)
    observations = np.asarray(raw["observations"], dtype=np.float32)
    actions = np.asarray(raw["actions"], dtype=np.float32)
    rewards = np.asarray(raw["rewards"], dtype=np.float32).reshape(-1)
    terminals = np.asarray(raw["terminals"], dtype=np.float32).reshape(-1)
    next_observations = np.asarray(raw["next_observations"], dtype=np.float32)

    if not (
        len(observations)
        == len(actions)
        == len(rewards)
        == len(terminals)
        == len(next_observations)
    ):
        raise ValueError("D4RL qlearning_dataset fields have inconsistent lengths.")

    # This is the same discontinuity test used by the local RLPD baseline to
    # recover episode boundaries after d4rl.qlearning_dataset filters timeouts.
    boundaries = np.zeros(len(rewards), dtype=bool)
    if len(rewards) > 1:
        diffs = np.linalg.norm(
            observations[1:] - next_observations[:-1], axis=-1
        )
        boundaries[:-1] = np.logical_or(diffs > 1e-6, terminals[:-1] > 0.5)
    if len(rewards) > 0:
        boundaries[-1] = True

    episodes: List[NumpyBatch] = []
    start = 0
    for index, is_boundary in enumerate(boundaries):
        if not is_boundary:
            continue
        end = index + 1
        episodes.append(
            _episode_to_arrays(
                observations[start:end],
                actions[start:end],
                rewards[start:end],
                next_observations[start:end],
                terminals[start:end] > 0.5,
                config,
            )
        )
        start = end

    return _concatenate_batches(episodes)


def _load_d4rl_dataset(env: gym.Env, config: TrainConfig) -> NumpyBatch:
    if _env_type(config.env_name) == "adroit_d4rl":
        return _load_standard_adroit_d4rl_dataset(env, config)

    candidate = env
    raw_dataset = None
    for _ in range(16):
        if hasattr(candidate, "get_dataset"):
            raw_dataset = candidate.get_dataset()
            break
        if not hasattr(candidate, "env"):
            break
        candidate = candidate.env
    if raw_dataset is None:
        raise AttributeError("The environment does not expose get_dataset().")

    observations = np.asarray(raw_dataset["observations"])
    actions = np.asarray(raw_dataset["actions"])
    rewards = np.asarray(raw_dataset["rewards"])
    terminals = np.asarray(raw_dataset["terminals"]).astype(bool)
    timeouts = (
        np.asarray(raw_dataset["timeouts"]).astype(bool)
        if "timeouts" in raw_dataset
        else None
    )
    next_observations_raw = raw_dataset.get("next_observations")
    horizon = _max_episode_steps(env, config.max_episode_steps)

    episodes: List[NumpyBatch] = []
    ep_obs: List[np.ndarray] = []
    ep_actions: List[np.ndarray] = []
    ep_rewards: List[float] = []
    ep_next_obs: List[np.ndarray] = []
    ep_terminals: List[bool] = []
    episode_step = 0

    for index in range(len(rewards)):
        timeout = (
            bool(timeouts[index])
            if timeouts is not None
            else episode_step == horizon - 1
        )
        terminal = bool(terminals[index])

        # Match the released loader: timeout transitions are not included.
        if not timeout and index != len(rewards) - 1:
            ep_obs.append(observations[index])
            ep_actions.append(actions[index])
            ep_rewards.append(float(rewards[index]))
            if next_observations_raw is not None:
                ep_next_obs.append(next_observations_raw[index])
            else:
                ep_next_obs.append(observations[index + 1])
            ep_terminals.append(terminal)

        episode_step += 1
        if terminal or timeout or index == len(rewards) - 1:
            if ep_rewards:
                episodes.append(
                    _episode_to_arrays(
                        ep_obs,
                        ep_actions,
                        ep_rewards,
                        ep_next_obs,
                        ep_terminals,
                        config,
                    )
                )
            ep_obs, ep_actions, ep_rewards = [], [], []
            ep_next_obs, ep_terminals = [], []
            episode_step = 0

    return _concatenate_batches(episodes)


def _binary_file_candidates(env_name: str, include_bc: bool) -> List[str]:
    name = env_name.lower()
    if "pen" in name:
        expert, bc = "pen2_sparse.npy", "pen_bc_sparse4.npy"
    elif "door" in name:
        expert, bc = "door2_sparse.npy", "door_bc_sparse4.npy"
    elif "relocate" in name:
        expert, bc = "relocate2_sparse.npy", "relocate_bc_sparse4.npy"
    else:
        raise ValueError("Adroit-Binary supports Pen, Door, and Relocate.")
    return [expert, bc] if include_bc else [expert]


def _extract_trajectory_field(trajectory, names: Sequence[str]):
    if isinstance(trajectory, Mapping):
        for name in names:
            if name in trajectory:
                return trajectory[name]
    for name in names:
        if hasattr(trajectory, name):
            return getattr(trajectory, name)
    raise KeyError(f"None of the fields {tuple(names)} were found.")


def _state_observation_array(values) -> np.ndarray:
    states = []
    for value in values:
        if isinstance(value, Mapping):
            value = value["state_observation"]
        states.append(np.asarray(value, dtype=np.float32))
    return np.asarray(states, dtype=np.float32)


def _load_adroit_binary_dataset(config: TrainConfig) -> NumpyBatch:
    if config.adroit_binary_data_dir is None:
        raise ValueError(
            "adroit_binary_data_dir must point to the downloaded "
            "offpolicy_hand_data directory."
        )
    root = Path(config.adroit_binary_data_dir)
    paths = [
        root / filename
        for filename in _binary_file_candidates(
            config.env_name, config.adroit_binary_include_bc
        )
    ]
    missing = [str(path) for path in paths if not path.exists()]
    if missing:
        raise FileNotFoundError("Missing Adroit data: " + ", ".join(missing))

    episodes: List[NumpyBatch] = []
    for path in paths:
        trajectories = np.load(path, allow_pickle=True)
        for trajectory in trajectories:
            if isinstance(trajectory, np.ndarray) and trajectory.shape == ():
                trajectory = trajectory.item()
            observations = _state_observation_array(
                _extract_trajectory_field(trajectory, ("observations", "observations_n"))
            )
            actions = np.asarray(
                _extract_trajectory_field(trajectory, ("actions",)), dtype=np.float32
            )
            rewards = np.asarray(
                _extract_trajectory_field(trajectory, ("rewards",)), dtype=np.float32
            ).squeeze()
            success_indices = np.flatnonzero(np.isclose(rewards, 0.0))
            if success_indices.size == 0:
                continue
            last = int(success_indices[-1])
            try:
                next_observations = _state_observation_array(
                    _extract_trajectory_field(
                        trajectory, ("next_observations", "next_observations_n")
                    )
                )
                current_obs = observations[: last + 1]
                next_obs = next_observations[: last + 1]
            except KeyError:
                current_obs = observations[: last + 1]
                next_obs = observations[1 : last + 2]
            kept_rewards = rewards[: last + 1]
            terminals = np.isclose(kept_rewards, 0.0)
            episodes.append(
                _episode_to_arrays(
                    current_obs,
                    actions[: last + 1],
                    kept_rewards,
                    next_obs,
                    terminals,
                    config,
                )
            )
    return _concatenate_batches(episodes)


class ArrayDataset:
    def __init__(self, arrays: Mapping[str, np.ndarray], seed: Optional[int] = None):
        lengths = {len(value) for value in arrays.values()}
        if not arrays or len(lengths) != 1:
            raise ValueError("Dataset fields must be nonempty and equal length.")
        self.arrays = {key: np.asarray(value) for key, value in arrays.items()}
        self.size = int(lengths.pop())
        self._np_random, self.seed_value = gym.utils.seeding.np_random(seed)

    def sample(self, batch_size: int) -> NumpyBatch:
        if hasattr(self._np_random, "integers"):
            indices = self._np_random.integers(self.size, size=batch_size)
        else:
            indices = self._np_random.randint(self.size, size=batch_size)
        return {key: value[indices] for key, value in self.arrays.items()}


class ReplayBuffer:
    def __init__(
        self,
        observation_space: gym.Space,
        action_space: gym.Space,
        capacity: int,
        seed: Optional[int] = None,
    ):
        if not isinstance(observation_space, gym.spaces.Box):
            raise TypeError("ReplayBuffer requires a flat Box observation space.")
        if not isinstance(action_space, gym.spaces.Box):
            raise TypeError("ReplayBuffer requires a Box action space.")
        self.capacity = int(capacity)
        self.size = 0
        self.insert_index = 0
        self.observations = np.empty(
            (capacity, *observation_space.shape), dtype=np.float32
        )
        self.next_observations = np.empty_like(self.observations)
        self.actions = np.empty((capacity, *action_space.shape), dtype=np.float32)
        self.rewards = np.empty((capacity,), dtype=np.float32)
        self.masks = np.empty((capacity,), dtype=np.float32)
        self.dones = np.empty((capacity,), dtype=bool)
        self._np_random, self.seed_value = gym.utils.seeding.np_random(seed)

    def insert(
        self,
        observation: np.ndarray,
        action: np.ndarray,
        reward: float,
        mask: float,
        done: bool,
        next_observation: np.ndarray,
    ) -> None:
        index = self.insert_index
        self.observations[index] = observation
        self.actions[index] = action
        self.rewards[index] = reward
        self.masks[index] = mask
        self.dones[index] = done
        self.next_observations[index] = next_observation
        self.insert_index = (index + 1) % self.capacity
        self.size = min(self.size + 1, self.capacity)

    def sample(self, batch_size: int) -> NumpyBatch:
        if self.size == 0:
            raise ValueError("Cannot sample from an empty replay buffer.")
        if hasattr(self._np_random, "integers"):
            indices = self._np_random.integers(self.size, size=batch_size)
        else:
            indices = self._np_random.randint(self.size, size=batch_size)
        return {
            "observations": self.observations[indices],
            "actions": self.actions[indices],
            "rewards": self.rewards[indices],
            "masks": self.masks[indices],
            "dones": self.dones[indices],
            "next_observations": self.next_observations[indices],
        }


