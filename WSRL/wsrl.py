def _init_linear_orthogonal(layer: nn.Linear, scale: float) -> None:
    nn.init.orthogonal_(layer.weight, gain=float(scale))
    if layer.bias is not None:
        nn.init.zeros_(layer.bias)


class NormalizedMLP(nn.Module):
    def __init__(
        self,
        input_dim: int,
        hidden_dims: Sequence[int],
        use_layer_norm: bool,
        layer_norm_eps: float,
        hidden_init_scale: float,
        final_hidden_init_scale: float,
    ):
        super().__init__()
        self.layers = nn.ModuleList()
        self.norms = nn.ModuleList()
        current_dim = input_dim
        for index, hidden_dim in enumerate(hidden_dims):
            layer = nn.Linear(current_dim, hidden_dim)
            scale = (
                final_hidden_init_scale
                if index == len(hidden_dims) - 1
                else hidden_init_scale
            )
            _init_linear_orthogonal(layer, scale)
            self.layers.append(layer)
            if use_layer_norm:
                self.norms.append(nn.LayerNorm(hidden_dim, eps=layer_norm_eps))
            current_dim = hidden_dim
        self.use_layer_norm = bool(use_layer_norm)
        self.output_dim = current_dim

    def forward(self, inputs: torch.Tensor) -> torch.Tensor:
        values = inputs
        for index, layer in enumerate(self.layers):
            values = layer(values)
            if self.use_layer_norm:
                values = self.norms[index](values)
            values = F.relu(values)
        return values


class TanhGaussianActor(nn.Module):
    def __init__(
        self,
        observation_dim: int,
        action_dim: int,
        hidden_dims: Sequence[int],
        std_parameterization: str,
        config: TrainConfig,
    ):
        super().__init__()
        self.trunk = NormalizedMLP(
            observation_dim,
            hidden_dims,
            config.use_layer_norm,
            config.layer_norm_eps,
            config.hidden_init_scale,
            config.final_hidden_init_scale,
        )
        self.mean = nn.Linear(self.trunk.output_dim, action_dim)
        _init_linear_orthogonal(self.mean, config.output_init_scale)
        self.std_parameterization = std_parameterization
        if std_parameterization == "exp":
            self.log_std_head = nn.Linear(self.trunk.output_dim, action_dim)
            _init_linear_orthogonal(self.log_std_head, config.output_init_scale)
            self.log_stds = None
        elif std_parameterization == "uniform":
            self.log_std_head = None
            self.log_stds = nn.Parameter(torch.zeros(action_dim))
        else:
            raise ValueError(f"Unsupported std_parameterization: {std_parameterization}")
        self.std_min = float(config.policy_std_min)
        self.std_max = float(config.policy_std_max)

    def distribution(self, observations: torch.Tensor) -> Normal:
        features = self.trunk(observations)
        mean = self.mean(features)
        if self.log_std_head is not None:
            std = self.log_std_head(features).exp()
        else:
            std = self.log_stds.exp().expand_as(mean)
        std = std.clamp(self.std_min, self.std_max)
        return Normal(mean, std)

    @staticmethod
    def _log_prob_from_pre_tanh(
        distribution: Normal, pre_tanh: torch.Tensor
    ) -> torch.Tensor:
        base_log_prob = distribution.log_prob(pre_tanh)
        correction = 2.0 * (
            math.log(2.0) - pre_tanh - F.softplus(-2.0 * pre_tanh)
        )
        return (base_log_prob - correction).sum(dim=-1)

    def sample(
        self,
        observations: torch.Tensor,
        repeat: Optional[int] = None,
        reparameterize: bool = True,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        if repeat is not None:
            observations = observations.unsqueeze(1).expand(
                observations.shape[0], repeat, observations.shape[-1]
            )
        distribution = self.distribution(observations)
        pre_tanh = (
            distribution.rsample() if reparameterize else distribution.sample()
        )
        actions = torch.tanh(pre_tanh)
        log_prob = self._log_prob_from_pre_tanh(distribution, pre_tanh)
        return actions, log_prob

    def mode(self, observations: torch.Tensor) -> torch.Tensor:
        return torch.tanh(self.distribution(observations).mean)

    @torch.no_grad()
    def sample_action(self, observation: np.ndarray, device: torch.device) -> np.ndarray:
        tensor = torch.as_tensor(
            observation, dtype=torch.float32, device=device
        ).unsqueeze(0)
        action, _ = self.sample(tensor, reparameterize=False)
        return action.squeeze(0).cpu().numpy()

    @torch.no_grad()
    def eval_action(self, observation: np.ndarray, device: torch.device) -> np.ndarray:
        tensor = torch.as_tensor(
            observation, dtype=torch.float32, device=device
        ).unsqueeze(0)
        return self.mode(tensor).squeeze(0).cpu().numpy()


class EnsembleLinear(nn.Module):
    """Independent dense layers evaluated as one vectorized ensemble."""

    def __init__(
        self,
        ensemble_size: int,
        input_dim: int,
        output_dim: int,
        init_scale: float,
    ):
        super().__init__()
        self.weight = nn.Parameter(
            torch.empty(ensemble_size, input_dim, output_dim)
        )
        self.bias = nn.Parameter(torch.zeros(ensemble_size, output_dim))
        for ensemble_index in range(ensemble_size):
            temporary = torch.empty(output_dim, input_dim)
            nn.init.orthogonal_(temporary, gain=float(init_scale))
            with torch.no_grad():
                self.weight[ensemble_index].copy_(temporary.transpose(0, 1))

    def forward_first(
        self,
        inputs: torch.Tensor,
        indices: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Map ``[B,...,I]`` to ``[E,B,...,O]``."""
        weight = self.weight if indices is None else self.weight.index_select(0, indices)
        bias = self.bias if indices is None else self.bias.index_select(0, indices)
        values = torch.einsum("b...i,eio->eb...o", inputs, weight)
        view_shape = (bias.shape[0],) + (1,) * (values.ndim - 2) + (bias.shape[-1],)
        return values + bias.view(view_shape)

    def forward_ensemble(
        self,
        inputs: torch.Tensor,
        indices: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Map ``[E,B,...,I]`` to ``[E,B,...,O]``."""
        weight = self.weight if indices is None else self.weight.index_select(0, indices)
        bias = self.bias if indices is None else self.bias.index_select(0, indices)
        values = torch.einsum("eb...i,eio->eb...o", inputs, weight)
        view_shape = (bias.shape[0],) + (1,) * (values.ndim - 2) + (bias.shape[-1],)
        return values + bias.view(view_shape)


class EnsembleLayerNorm(nn.Module):
    def __init__(self, ensemble_size: int, feature_dim: int, eps: float):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(ensemble_size, feature_dim))
        self.bias = nn.Parameter(torch.zeros(ensemble_size, feature_dim))
        self.eps = float(eps)

    def forward(
        self,
        inputs: torch.Tensor,
        indices: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        weight = self.weight if indices is None else self.weight.index_select(0, indices)
        bias = self.bias if indices is None else self.bias.index_select(0, indices)
        mean = inputs.mean(dim=-1, keepdim=True)
        variance = (inputs - mean).pow(2).mean(dim=-1, keepdim=True)
        normalized = (inputs - mean) * torch.rsqrt(variance + self.eps)
        view_shape = (weight.shape[0],) + (1,) * (inputs.ndim - 2) + (weight.shape[-1],)
        return normalized * weight.view(view_shape) + bias.view(view_shape)


class CriticEnsemble(nn.Module):
    def __init__(
        self,
        observation_dim: int,
        action_dim: int,
        hidden_dims: Sequence[int],
        ensemble_size: int,
        config: TrainConfig,
    ):
        super().__init__()
        self.ensemble_size = int(ensemble_size)
        self.hidden_layers = nn.ModuleList()
        self.layer_norms = nn.ModuleList()
        input_dim = observation_dim + action_dim
        for layer_index, hidden_dim in enumerate(hidden_dims):
            init_scale = (
                config.final_hidden_init_scale
                if layer_index == len(hidden_dims) - 1
                else config.hidden_init_scale
            )
            self.hidden_layers.append(
                EnsembleLinear(
                    self.ensemble_size,
                    input_dim,
                    hidden_dim,
                    init_scale,
                )
            )
            if config.use_layer_norm:
                self.layer_norms.append(
                    EnsembleLayerNorm(
                        self.ensemble_size,
                        hidden_dim,
                        config.layer_norm_eps,
                    )
                )
            input_dim = hidden_dim
        self.output_layer = EnsembleLinear(
            self.ensemble_size,
            input_dim,
            1,
            config.output_init_scale,
        )
        self.use_layer_norm = bool(config.use_layer_norm)

    def forward(
        self,
        observations: torch.Tensor,
        actions: torch.Tensor,
        indices: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        if actions.ndim == observations.ndim + 1:
            observations = observations.unsqueeze(1).expand(
                observations.shape[0], actions.shape[1], observations.shape[-1]
            )
        values = torch.cat([observations, actions], dim=-1)
        for layer_index, layer in enumerate(self.hidden_layers):
            if layer_index == 0:
                values = layer.forward_first(values, indices=indices)
            else:
                values = layer.forward_ensemble(values, indices=indices)
            if self.use_layer_norm:
                values = self.layer_norms[layer_index](values, indices=indices)
            values = F.relu(values)
        values = self.output_layer.forward_ensemble(values, indices=indices)
        return values.squeeze(-1)


