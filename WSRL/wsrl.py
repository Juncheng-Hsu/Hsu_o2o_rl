def _convert_observation_to_float32(observation):
    if isinstance(observation, np.ndarray) and observation.dtype == np.float64:
        return observation.astype(np.float32)
    if isinstance(observation, dict):
        return {k: _convert_observation_to_float32(v) for k, v in observation.items()}
    return observation


class SinglePrecision(gym.ObservationWrapper):
    def __init__(self, env: gym.Env):
        super().__init__(env)
        space = env.observation_space
        if isinstance(space, gym.spaces.Box):
            self.observation_space = gym.spaces.Box(
                low=space.low,
                high=space.high,
                shape=space.shape,
                dtype=np.float32,
            )
        elif isinstance(space, gym.spaces.Dict):
            converted = {}
            for key, subspace in space.spaces.items():
                if not isinstance(subspace, gym.spaces.Box):
                    raise NotImplementedError("Only Box entries are supported.")
                converted[key] = gym.spaces.Box(
                    low=subspace.low,
                    high=subspace.high,
                    shape=subspace.shape,
                    dtype=np.float32,
                )
            self.observation_space = gym.spaces.Dict(converted)
        else:
            raise NotImplementedError(f"Unsupported observation space: {type(space)}")

    def observation(self, observation):
        return _convert_observation_to_float32(observation)


class RewardTransform(gym.RewardWrapper):
    def __init__(self, env: gym.Env, scale: float, bias: float):
        super().__init__(env)
        self.scale = float(scale)
        self.bias = float(bias)

    def reward(self, reward):
        return float(reward) * self.scale + self.bias


class UniversalSeed(gym.Wrapper):
    def seed(self, seed: int):
        result = None
        try:
            result = self.env.seed(seed)
        except Exception:
            pass
        try:
            self.env.observation_space.seed(seed)
            self.env.action_space.seed(seed)
        except Exception:
            pass
        return result


class AdroitTerminalWrapper(gym.Wrapper):
    """Match the released WSRL Adroit-Binary success termination rule only."""

    def step(self, action):
        output = self.env.step(action)
        if len(output) == 5:
            observation, reward, terminated, truncated, info = output
            if bool(info.get("goal_achieved", False)):
                terminated = True
            return observation, reward, terminated, truncated, info
        observation, reward, done, info = output
        if bool(info.get("goal_achieved", False)):
            done = True
        return observation, reward, done, info


class KitchenTerminalWrapper(gym.Wrapper):
    """Match the released WSRL Kitchen completion termination rule."""

    def step(self, action):
        output = self.env.step(action)
        if len(output) == 5:
            observation, reward, terminated, truncated, info = output
            if float(reward) == 4.0:
                terminated = True
            return observation, reward, terminated, truncated, info
        observation, reward, done, info = output
        if float(reward) == 4.0:
            done = True
        return observation, reward, done, info


def wrap_env(env: gym.Env, config: TrainConfig, training: bool) -> gym.Env:
    env_type = _env_type(config.env_name)

    # Released WSRL applies these terminal fixes immediately after gym.make().
    if env_type == "adroit_binary":
        env = AdroitTerminalWrapper(env)
    elif env_type == "kitchen":
        env = KitchenTerminalWrapper(env)

    env = SinglePrecision(env)
    env = UniversalSeed(env)
    if env_type in {"antmaze", "kitchen", "locomotion", "adroit_d4rl"}:
        # Standard D4RL Adroit follows the same rescaled-action interface used
        # by the RLPD benchmark; official Adroit-Binary keeps its released path.
        # Match released make_gym_env for the other WSRL domains: expose the policy action space as
        # [-clip_action, clip_action], then rescale to the base env bounds.
        env = gym.wrappers.RescaleAction(
            env, -float(config.clip_action), float(config.clip_action)
        )
    if isinstance(env.observation_space, gym.spaces.Dict):
        env = gym.wrappers.FlattenObservation(env)
    if env_type in {"antmaze", "kitchen", "locomotion", "adroit_d4rl"}:
        env = gym.wrappers.ClipAction(env)
    if training:
        env = RewardTransform(env, float(config.reward_scale), float(config.reward_bias))
    try:
        env = gym.wrappers.RecordEpisodeStatistics(env)
    except Exception:
        pass
    return env


def _seed_env(env: gym.Env, seed: int) -> None:
    try:
        env.seed(seed)
    except Exception:
        try:
            env.reset(seed=seed)
        except Exception:
            pass
    try:
        env.action_space.seed(seed)
        env.observation_space.seed(seed)
    except Exception:
        pass


def _reset_env(env: gym.Env, seed: Optional[int] = None):
    try:
        output = env.reset(seed=seed) if seed is not None else env.reset()
    except TypeError:
        if seed is not None:
            _seed_env(env, seed)
        output = env.reset()
    return output[0] if isinstance(output, tuple) else output


def _step_env(env: gym.Env, action):
    output = env.step(action)
    if len(output) == 5:
        next_observation, reward, terminated, truncated, info = output
        return (
            next_observation,
            float(reward),
            bool(terminated),
            bool(truncated),
            dict(info),
        )
    next_observation, reward, done, info = output
    info = dict(info)
    truncated = bool(info.get("TimeLimit.truncated", False))
    terminated = bool(done and not truncated)
    return next_observation, float(reward), terminated, truncated, info


def _max_episode_steps(env: gym.Env, override: Optional[int]) -> int:
    if override is not None:
        return int(override)
    candidate = env
    for _ in range(16):
        value = getattr(candidate, "_max_episode_steps", None)
        if value is not None:
            return int(value)
        spec = getattr(candidate, "spec", None)
        if spec is not None and getattr(spec, "max_episode_steps", None) is not None:
            return int(spec.max_episode_steps)
        if not hasattr(candidate, "env"):
            break
        candidate = candidate.env
    return 1_000


